import fs from 'fs';
import path from 'path';
import { spawn } from 'child_process';
import { v4 as uuidv4 } from 'uuid';
import { config } from './config.js';

// Ensure temp directory exists
if (!fs.existsSync(config.tempDir)) {
  fs.mkdirSync(config.tempDir, { recursive: true });
}

/**
 * Compiles LaTeX source text into a PDF buffer using Tectonic.
 *
 * @param {string} latexSource The LaTeX source code.
 * @param {object} options Optional compilation options.
 * @returns {Promise<{ pdfBuffer: Buffer, latexSource: string, logs: string, durationMs: number }>}
 */
export async function compileLatexToPdf(latexSource, options = {}) {
  if (!latexSource || typeof latexSource !== 'string' || latexSource.trim().length === 0) {
    throw new Error('LaTeX content is empty or invalid.');
  }

  const jobId = uuidv4();
  const jobDir = path.join(config.tempDir, jobId);
  const inputTexPath = path.join(jobDir, 'document.tex');
  const outputPdfPath = path.join(jobDir, 'document.pdf');

  const startTime = Date.now();

  try {
    await fs.promises.mkdir(jobDir, { recursive: true });
    await fs.promises.writeFile(inputTexPath, latexSource, 'utf-8');

    // Execute Tectonic compiler
    // Tectonic compiles document.tex and outputs document.pdf directly into jobDir
    const isOffline = options.offline === true || (options.offline !== false && config.offlineMode);

    const args = [
      inputTexPath,
      '--outdir', jobDir,
      '--chatter', 'minimal',
      '--untrusted'
    ];

    if (isOffline) {
      args.push('--only-cached');
    }

    const { stdout, stderr, exitCode } = await new Promise((resolve, reject) => {
      let stdoutData = '';
      let stderrData = '';
      let timedOut = false;

      const proc = spawn(config.tectonicPath, args, {
        cwd: jobDir,
        windowsHide: true,
        stdio: ['ignore', 'pipe', 'pipe'] // Ensure stdin never blocks on interactive prompts
      });

      const timeoutSec = Math.round(config.compilationTimeoutMs / 1000);
      const timeout = setTimeout(() => {
        timedOut = true;
        proc.kill('SIGKILL');
        reject(new Error(`Compilation timed out after ${timeoutSec} seconds. If your document uses new packages, they may have taken too long to download from the CTAN network. Try recompiling or increase COMPILATION_TIMEOUT_MS.`));
      }, config.compilationTimeoutMs);

      proc.stdout.on('data', (data) => {
        stdoutData += data.toString();
      });

      proc.stderr.on('data', (data) => {
        stderrData += data.toString();
      });

      proc.on('error', (err) => {
        clearTimeout(timeout);
        if (!timedOut) {
          reject(new Error(`Failed to start Tectonic compiler at "${config.tectonicPath}": ${err.message}`));
        }
      });

      proc.on('close', (code) => {
        clearTimeout(timeout);
        if (!timedOut) {
          resolve({ stdout: stdoutData, stderr: stderrData, exitCode: code });
        }
      });
    });

    const logs = (stdout + '\n' + stderr).trim();

    if (exitCode !== 0) {
      const errorMsg = extractLatexError(logs) || `LaTeX compilation failed with exit code ${exitCode}`;
      const err = new Error(errorMsg);
      err.logs = logs;
      err.exitCode = exitCode;
      throw err;
    }

    if (!fs.existsSync(outputPdfPath)) {
      const err = new Error('PDF output file was not generated by Tectonic.');
      err.logs = logs;
      throw err;
    }

    const pdfBuffer = await fs.promises.readFile(outputPdfPath);
    const durationMs = Date.now() - startTime;

    return {
      pdfBuffer,
      latexSource,
      logs,
      durationMs,
      jobId
    };
  } finally {
    // Clean up temporary job directory
    try {
      if (fs.existsSync(jobDir)) {
        await fs.promises.rm(jobDir, { recursive: true, force: true });
      }
    } catch (cleanupErr) {
      console.error(`Warning: Failed to cleanup temp directory ${jobDir}:`, cleanupErr.message);
    }
  }
}

/**
 * Extracts relevant error lines from LaTeX / Tectonic compilation logs.
 */
function extractLatexError(logs) {
  if (!logs) return null;
  const lines = logs.split(/\r?\n/).filter(line => !line.toLowerCase().includes('fontconfig error'));
  const errorLines = lines.filter(line => 
    line.startsWith('!') || 
    line.toLowerCase().includes('error:') ||
    line.toLowerCase().includes('fatal error')
  );
  if (errorLines.length > 0) {
    return errorLines.slice(0, 5).join('\n');
  }
  return null;
}
